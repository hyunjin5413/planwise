import { describe, expect, it } from "vitest";
import { jo } from "@/lib/engine/korean";

describe("조사 선택", () => {
  it.each([
    ["사무실 B", "은/는", "사무실 B는"],
    ["경종", "을/를", "경종을"],
    ["피난구유도등", "이/가", "피난구유도등이"],
    ["발신기", "이/가", "발신기가"],
    ["복도", "이/가", "복도가"],
    ["계단실1", "은/는", "계단실1은"],
    ["계단실2", "은/는", "계단실2는"],
    ["회의실", "으로/로", "회의실로"],
    ["창고", "으로/로", "창고로"],
    ["사무실(대)", "은/는", "사무실(대)은"],
  ] as const)("%s + %s → %s", (w, p, out) => expect(jo(w, p)).toBe(out));
});
